// Блок ChatGPT для детальной (платной, $30) проверки.
// НЕ влияет на процент готовности AIRS. Показывает клиенту, кого ChatGPT
// рекомендует в его нише — как побудитель заказать доработку.
//
// Сейчас ключа к API нет, поэтому в отчёте показывается ПОСТОЯННЫЙ ответ
// (заглушка) в утверждённом формате. Когда появится ключ — заменить
// getChatgptBlock() на реальный вызов модели с промтом CHATGPT_PROMPT.
// Модель: текущая по умолчанию в ChatGPT, через API под именем chat-latest,
// с включённым поиском в интернете.
//
// Подаётся как пример ответа, а не гарантия: ответы модели у разных
// пользователей различаются.

// ==================== УТВЕРЖДЁННЫЙ ПРОМТ ====================
// Адрес проверяемого сайта подставляется в конец при реальном вызове.
export const CHATGPT_PROMPT = `Проанализируй сайт и определи категорию бизнеса. Если категорию определить невозможно — сообщи об этом. Не используй анализируемый сайт как кандидата для рекомендаций. Он нужен только для определения категории бизнеса и рынка (город, регион, страна или международный уровень).
Затем сформулируй естественный вопрос, который обычный пользователь, скорее всего, задал бы ChatGPT при поиске таких услуг. Используй уровень рынка, а не более узкую географию, если она не является единственным рынком бизнеса. Не используй в вопросе профессиональные термины или названия категорий бизнеса. Например, вместо «Какой ресторан высокой кухни вы порекомендуете?» напиши «Какой хороший итальянский ресторан вы порекомендуете в Майами?».
Используя поиск в интернете, назови три компании, которые ты с наибольшей вероятностью порекомендовал бы в ответ на этот вопрос. Для каждой компании укажи только название и город или район, в котором она находится. Включай анализируемый сайт только в том случае, если он действительно является одной из наиболее вероятных рекомендаций.
После списка одним коротким предложением простыми словами объясни, почему ты выбрал именно эти компании. Не объясняй, как работает ChatGPT, не используй рекламные формулировки, слова «репутация», «лидер», «авторитет», «качество», «признание», «рейтинг» и подобные общие оценки.
Ответ оформи строго в следующем формате:
**Категория бизнеса:** ...
**Рынок:** ...
**Наиболее вероятный вопрос пользователя к ChatGPT:**
*«...»*
**Я рекомендую:**
1. Компания — Город или район
2. Компания — Город или район
3. Компания — Город или район
**Почему именно они?**
*Потому что именно эти компании я бы сейчас с наибольшей вероятностью порекомендовал человеку, который ищет такие услуги.*`;

// ==================== СТРУКТУРА ОТВЕТА ====================
export interface ChatgptBlock {
  category: string;
  market: string;
  question: string;
  companies: { name: string; place: string }[];
  reason: string;
}

// ==================== ПОСТОЯННЫЙ ОТВЕТ (заглушка) ====================
// Реальный ответ ChatGPT из наших тестов на sofiamiamidd.com.
const STUB_BLOCK: ChatgptBlock = {
  category: "Итальянский ресторан",
  market: "Майами, Флорида, США",
  question: "Какой хороший итальянский ресторан вы порекомендуете в Майами?",
  companies: [
    { name: "Carbone", place: "South Beach" },
    { name: "Boia De", place: "Little Haiti" },
    { name: "Macchialina", place: "South Beach" },
  ],
  reason:
    "Потому что именно эти компании я бы сейчас с наибольшей вероятностью порекомендовал человеку, который ищет такие услуги.",
};

// Возвращает блок для показа. Пока — постоянная заглушка.
// Позже здесь будет реальный вызов модели по адресу url.
export function getChatgptBlock(_url?: string): ChatgptBlock {
  return STUB_BLOCK;
}

// Готовый HTML блока для вставки в PDF-шаблон (плейсхолдер {{chatgpt_block}}).
export function getChatgptBlockHtml(url?: string): string {
  const b = getChatgptBlock(url);
  const rows = b.companies
    .map(
      (c, i) =>
        `<li style="margin:2px 0;">${i + 1}. <strong>${c.name}</strong> — ${c.place}</li>`
    )
    .join("");
  return `
  <div style="border:1px solid #e5e7eb;border-radius:12px;padding:16px 18px;margin:18px 0;background:#f9fafb;">
    <div style="font-weight:700;font-size:14px;color:#111827;margin-bottom:10px;">
      Кого ChatGPT рекомендует в вашей нише
    </div>
    <div style="font-size:13px;color:#1f2937;line-height:1.6;">
      <div><strong>Категория бизнеса:</strong> ${b.category}</div>
      <div><strong>Рынок:</strong> ${b.market}</div>
      <div style="margin-top:6px;"><strong>Наиболее вероятный вопрос пользователя к ChatGPT:</strong></div>
      <div style="font-style:italic;color:#374151;">«${b.question}»</div>
      <div style="margin-top:6px;"><strong>Я рекомендую:</strong></div>
      <ol style="list-style:none;padding-left:0;margin:4px 0;">${rows}</ol>
      <div style="margin-top:6px;"><strong>Почему именно они?</strong></div>
      <div style="font-style:italic;color:#374151;">${b.reason}</div>
    </div>
    <div style="margin-top:10px;font-size:11px;color:#9ca3af;">
      Пример ответа ChatGPT. Проверка выполняется только по информации на самом сайте; ответы модели у разных пользователей могут различаться.
    </div>
  </div>`;
}
