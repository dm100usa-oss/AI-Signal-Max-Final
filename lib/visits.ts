// Базовая часть счётчика посетителей.
// Назначение: социальное доказательство. Число стартует с BASE и плавно растёт
// со временем, чтобы вернувшийся посетитель видел изменение. Реальные заходы
// (из Redis) прибавляются поверх этой базы на стороне клиента.

const BASE = 1020;

// Точка отсчёта роста. Не меняй после публикации — иначе число «прыгнет».
const ANCHOR = Date.UTC(2026, 5, 25, 0, 0, 0); // 25 июня 2026, UTC

// Средний прирост базы в час (правдоподобная «активность» сайта).
const PER_HOUR = 4;

// Возвращает базовое число посетителей на текущий момент.
// Формула без цикла: считается мгновенно и не дорожает со временем.
export function baseVisitors(now: number = Date.now()): number {
  const hours = Math.max(0, Math.floor((now - ANCHOR) / 3_600_000));
  // детерминированная «рябь» поверх ровного роста, чтобы число не выглядело механически
  const wobble = Math.floor((Math.sin(hours * 0.7) + 1) * 1.5); // 0..3
  return BASE + hours * PER_HOUR + wobble;
}
